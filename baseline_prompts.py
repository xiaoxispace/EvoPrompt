import argparse
import random
import torch

from tqdm import tqdm
from pathlib import Path

from utils.inference_utils import generate
from utils.population_utils import evaluate_population
from utils.utils import set_seed, prepare_model, proportion_of_symbols, load_config, load_text


if __name__ == "__main__":
  argparser = argparse.ArgumentParser()
  argparser.add_argument('-t', '--eval-times', type=int, default=1)
  argparser.add_argument('-c', '--config-path', type=Path, default="config.json")
  parser = argparser.parse_args()
  eval_times = parser.eval_times
  config_path = parser.config_path

  model_path = Path("checkpoints/ctx384-3e-5/best_model_ctx384_d256_L3_H4_lr3e-05_dropout1e-01_e47.pth")
  model, tokenizer, config = prepare_model(model_path)
  device = 'cuda' if torch.cuda.is_available() else 'cpu'

  config = load_config(config_path, "baseline")
  training_data_path = config["training-data-path"]
  text = load_text(training_data_path)
  text_length = len(text)

  print(f"In training text, the proportion of symbols is: {proportion_of_symbols(text)}")

  n = config["n"]
  d = config["d"]
  seed = config["seeds"][0]
  set_seed(seed)

  def fitness_func(individual):
    output_token_ids = generate(model, individual, length = 3*d, device=device)
    output_text = tokenizer.decode(output_token_ids)
    return proportion_of_symbols(output_text)

  for _ in range(eval_times):
    population = []
    for _ in range(n):
      s = random.randint(0, text_length - d)
      population.append(tokenizer.encode(text[s: s+d]))
    # evaluate only the initial population generated by symbols
    max_f, best_prompt_tokens, fitness_scores = evaluate_population(population, fitness_func)
    print("  Max fitness score: ", max_f)
    print("  Output text with max_f: ", tokenizer.decode(best_prompt_tokens))
