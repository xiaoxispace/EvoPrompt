import argparse
import torch

from pathlib import Path

from utils.inference_utils import generate
from utils.population_utils import generate_population, evaluate_population
from utils.utils import set_seed, prepare_model, proportion_of_symbols


if __name__ == "__main__":
  argparser = argparse.ArgumentParser()
  argparser.add_argument('-t', '--eval-times', type=int, default=100)
  parser = argparser.parse_args()
  eval_times = parser.eval_times
  seed = 496
  set_seed(seed)

  model_path = Path("checkpoints/ctx384-3e-5/best_model_ctx384_d256_L3_H4_lr3e-05_dropout1e-01_e47.pth")
  model, tokenizer, config = prepare_model(model_path)
  device = 'cuda' if torch.cuda.is_available() else 'cpu'

  n = 100
  d = config["block_size"]

  def fitness_func(individual):
    output_token_ids = generate(model, individual, length = 3*d, device=device)
    output_text = tokenizer.decode(output_token_ids)
    return proportion_of_symbols(output_text)

  vocab_to_ind = tokenizer.vocab_to_ind

  # evaluate only the initial population generated by symbols
  genes = list(i for k, i in vocab_to_ind.items() if not k.isalnum())
  population = generate_population(n, d, genes)
  max_f, best_prompt_tokens, fitness_scores = evaluate_population(population, fitness_func)
  print("Uniformly sampling only the symbols: ")
  print("  Max fitness score: ", max_f)
  print("  Output text with max_f: ", tokenizer.decode(best_prompt_tokens))

  # evaluate the initial population generated by sampling all characters
  genes = list(i for _, i in vocab_to_ind.items())
  population = generate_population(n, d, genes)
  max_f, best_prompt_tokens, fitness_scores = evaluate_population(population, fitness_func)
  print("Uniformly sampling all tokens: ")
  print("  Max fitness score: ", max_f)
  print("  Output text with max_f: ", tokenizer.decode(best_prompt_tokens))
